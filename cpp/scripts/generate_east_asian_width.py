"""Generates src/core/east_asian_width.inc from Python's unicodedata.

The table follows the running interpreter's Unicode version:
    python scripts/generate_east_asian_width.py
"""
import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "core" / "east_asian_width.inc"


def wide_ranges():
    ranges = []
    start = None
    for code in range(sys.maxunicode + 1):
        wide = unicodedata.east_asian_width(chr(code)) in ("W", "F")
        if wide and start is None:
            start = code
        elif not wide and start is not None:
            ranges.append((start, code - 1))
            start = None
    if start is not None:
        ranges.append((start, sys.maxunicode))
    return ranges


def main():
    lines = [
        f"// Generated by scripts/generate_east_asian_width.py from Unicode {unicodedata.unidata_version}; do not hand edit.",
        "// Inclusive code point ranges whose East Asian Width is W or F.",
    ]
    lines += [f"{{0x{a:X}, 0x{b:X}}}," for a, b in wide_ranges()]
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines) - 2} ranges -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
