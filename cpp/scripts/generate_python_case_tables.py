"""Generates src/core/py_case_tables.inc: str case mappings and properties of the reference interpreter.

Run with the reference interpreter so the Unicode version matches the Python build:
    ../venv311/Scripts/python.exe -I scripts/generate_python_case_tables.py

The mappings are the full ones str.lower() / upper() / title() / casefold() apply to a single
code point (U+03A3 maps to plain sigma; the final sigma rule needs the context). The
properties are the ones str methods test: Lowercase, Uppercase, Cased and Case_Ignorable.
"""
import pathlib
import sys

sys.dont_write_bytecode = True
import unicodedata  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "core" / "py_case_tables.inc"
SIGMA, FINAL_SIGMA = "σ", "ς"


def ranges(predicate):
    result, start = [], None
    for code in range(sys.maxunicode + 2):
        hit = code <= sys.maxunicode and predicate(chr(code))
        if hit and start is None:
            start = code
        elif not hit and start is not None:
            result.append((start, code - 1))
            start = None
    return result


def is_cased(c):
    # A lone cased character is lowercase or titled (istitle() also accepts uppercase).
    return c.islower() or c.istitle()


def is_case_ignorable(c):
    # Read back through the final sigma rule, which skips case-ignorable characters on both sides.
    if is_cased(c):
        return ("AΣ" + c).lower()[1] == FINAL_SIGMA
    return ("A" + c + "Σ").lower()[-1] == FINAL_SIGMA


def mapping(name, function):
    entries = []
    for code in range(sys.maxunicode + 1):
        if 0xD800 <= code <= 0xDFFF:
            continue
        c = chr(code)
        mapped = function(c)
        if mapped != c:
            assert 1 <= len(mapped) <= 3, (hex(code), mapped)
            points = [ord(m) for m in mapped] + [0] * (3 - len(mapped))
            entries.append(f"{{0x{code:X}, {{0x{points[0]:X}, 0x{points[1]:X}, 0x{points[2]:X}}}}},")
    return [f"// {name}: {len(entries)} code points.", f"constexpr CaseMapping {name}[] = {{", *entries, "};"]


def range_table(name, values):
    return [f"constexpr CodeRange {name}[] = {{", *(f"{{0x{a:X}, 0x{b:X}}}," for a, b in values), "};"]


def main():
    lines = [
        f"// Generated by scripts/generate_python_case_tables.py from Unicode {unicodedata.unidata_version}; do not hand edit.",
        "// Mappings list (code point, up to three code points, zero padded), sorted; properties are inclusive ranges.",
    ]
    lines += mapping("LOWER_MAPPINGS", lambda c: SIGMA if c == "Σ" else c.lower())
    lines += mapping("UPPER_MAPPINGS", str.upper)
    lines += mapping("TITLE_MAPPINGS", str.title)
    lines += mapping("FOLD_MAPPINGS", str.casefold)
    lines += range_table("LOWERCASE_RANGES", ranges(str.islower))
    lines += range_table("UPPERCASE_RANGES", ranges(str.isupper))
    lines += range_table("CASED_RANGES", ranges(is_cased))
    lines += range_table("CASE_IGNORABLE_RANGES", ranges(is_case_ignorable))
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines)} lines -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
