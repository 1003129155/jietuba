"""Generates src/core/html_entities.inc from the reference interpreter's html module.

Run with the reference interpreter so the tables match the Python build:
    python scripts/generate_html_entities.py
"""
import html
import html.entities
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "core" / "html_entities.inc"


def c_str(text):
    return '"' + "".join("\\x%02x" % b for b in text.encode("utf-8")) + '"'


def main():
    lines = ["// Generated by scripts/generate_html_entities.py; do not hand edit.",
             "static const HtmlEntity kHtml5Entities[] = {"]
    for name in sorted(html.entities.html5):
        lines.append("    {%s, %s}," % (c_str(name), c_str(html.entities.html5[name])))
    lines.append("};")
    lines.append("static const InvalidCharref kInvalidCharrefs[] = {")
    for num in sorted(html._invalid_charrefs):
        lines.append("    {0x%x, 0x%x}," % (num, ord(html._invalid_charrefs[num])))
    lines.append("};")
    lines.append("static const char32_t kInvalidCodepoints[] = {")
    lines.append("    " + ", ".join("0x%x" % c for c in sorted(html._invalid_codepoints)))
    lines.append("};")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
