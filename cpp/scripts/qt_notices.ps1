param(
    [Parameter(Mandatory)][string]$QtRoot,
    # Qt files in the build, named as in the SBOM: ./bin/Qt6Core.dll, ./lib/Qt6Core.lib, ./plugins/<type>/<name>.dll or .lib.
    [Parameter(Mandatory)][string[]]$Files,
    # License texts named <SPDX identifier>.txt; shipped beside the notices.
    [Parameter(Mandatory)][string]$LicenseDir,
    [Parameter(Mandatory)][string]$Output
)
# Third-party notices for the Qt files a build ships, from the SDK's SBOM (tag-value SPDX): the
# packages that contain the files and everything they depend on.
$ErrorActionPreference = 'Stop'

$packages = @{}
$fileIds = @{}
$owner = @{}
$deps = @{}
$sboms = @(Get-ChildItem -LiteralPath (Join-Path $QtRoot 'sbom') -Filter '*.spdx' | Where-Object { $_.Name -notlike '*.source.spdx' })
if (-not $sboms) { throw "No SBOM under $QtRoot\sbom" }
foreach ($sbom in $sboms) {
    $lines = [IO.File]::ReadAllLines($sbom.FullName)
    $record = $null
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -notmatch '^(\w+): (.*)$') { continue }
        $key = $Matches[1]
        $value = $Matches[2]
        if ($value.StartsWith('<text>')) {
            $value = $value.Substring(6)
            while ($value.IndexOf('</text>') -lt 0) { $i++; $value += "`n" + $lines[$i] }
            $value = $value.Substring(0, $value.IndexOf('</text>'))
        }
        if ($key -eq 'PackageName' -or $key -eq 'FileName' -or $key -eq 'LicenseID') {
            $record = @{ Kind = $key; Name = $value }
        } elseif ($key -eq 'Relationship') {
            # Other documents' elements are referenced as DocumentRef-<doc>:<id>; ids are unique across Qt's SBOMs.
            $from, $type, $to = $value -split ' ' | ForEach-Object { $_ -replace '^DocumentRef-[^:]+:', '' }
            if ($type -eq 'CONTAINS') { $owner[$to] = $from }
            if ($type -eq 'DEPENDS_ON') { $deps[$from] = @($deps[$from]) + $to }
        } elseif ($key -eq 'SPDXID' -and $record) {
            if ($record.Kind -eq 'PackageName') { $packages[$value] = $record }
            if ($record.Kind -eq 'FileName') { $fileIds[$record.Name] = $value }
        } elseif ($record -and -not $record.ContainsKey($key)) {
            $record[$key] = $value
        }
    }
}

$shipped = foreach ($file in $Files) {
    if ($fileIds.ContainsKey($file)) { $owner[$fileIds[$file]]; continue }
    # Some static libraries are listed only as their package (Qt6EntryPoint.lib as EntryPointPrivate).
    $module = [IO.Path]::GetFileNameWithoutExtension($file) -replace '^Qt6', ''
    $match = @($packages.Keys | Where-Object { $_ -like '*-qt-module-*' -and $packages[$_].Name -in @($module, "${module}Private") })
    if ($match.Count -ne 1) { throw "$file is not in the Qt SBOM" }
    $match[0]
}
$seen = @{}
$queue = New-Object System.Collections.Queue
foreach ($id in $shipped) { $queue.Enqueue($id) }
while ($queue.Count) {
    $id = $queue.Dequeue()
    if ($seen.ContainsKey($id)) { continue }
    $seen[$id] = $true
    foreach ($dep in @($deps[$id])) { if ($dep) { $queue.Enqueue($dep) } }
}

function Get-DisplayName($package) {
    if ($package.PackageComment -match '(?m)^\s*Name: (.+)$') { return $Matches[1].Trim() }
    return $package.Name
}

$qt = @($shipped | Where-Object { $_ -match '-qt-(module|plugin)-' } | Sort-Object -Unique | ForEach-Object { $packages[$_] } | Sort-Object { $_.Name })
# Qt's own copies of a library (ZlibPrivate beside BundledZLIB) carry the same notice; list it once.
$components = [ordered]@{}
$seen.Keys | Where-Object { $_ -match '-qt-(bundled-3rdparty-module|3rdparty-sources)-' } | ForEach-Object { $packages[$_] } |
    Sort-Object { (Get-DisplayName $_).ToLowerInvariant() }, { $_.Name } | ForEach-Object {
        $key = "$($_.PackageLicenseConcluded)`n$($_.PackageCopyrightText)"
        if (-not $components.Contains($key)) { $components[$key] = $_ }
    }

$licenses = @{}
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('QT THIRD-PARTY NOTICES')
[void]$out.AppendLine()
[void]$out.AppendLine('Generated by scripts/qt_notices.ps1 from the Qt SDK''s SBOM for the Qt files in this build.')
[void]$out.AppendLine('License texts are in licenses/qt/<SPDX identifier>.txt.')
[void]$out.AppendLine()
[void]$out.AppendLine("Qt $($qt[0].PackageVersion) modules and plugins in this build ($($qt[0].PackageLicenseConcluded)):")
foreach ($package in $qt) {
    $line = "  $($package.Name)"
    if ($package.PackageLicenseConcluded -ne $qt[0].PackageLicenseConcluded) { $line += " ($($package.PackageLicenseConcluded))" }
    [void]$out.AppendLine($line)
}
foreach ($package in $components.Values) {
    $expression = $package.PackageLicenseConcluded
    foreach ($id in [regex]::Matches($expression, '[A-Za-z0-9.+-]+') | ForEach-Object Value) {
        if ($id -notin @('AND', 'OR', 'WITH')) { $licenses[$id] = $true }
    }
    [void]$out.AppendLine()
    [void]$out.AppendLine('=' * 80)
    $version = if ($package.PackageVersion -and $package.PackageVersion -ne 'unknown') { " $($package.PackageVersion)" } else { '' }
    [void]$out.AppendLine("$(Get-DisplayName $package)$version  [Qt: $($package.Name)]")
    [void]$out.AppendLine("License: $expression")
    [void]$out.AppendLine()
    [void]$out.AppendLine("$($package.PackageCopyrightText)".Trim())
}
$missing = @($licenses.Keys | Where-Object { -not (Test-Path -LiteralPath (Join-Path $LicenseDir "$_.txt")) } | Sort-Object)
if ($missing) { throw "License texts missing from ${LicenseDir}: $($missing -join ', ') (copy them from the Qt sources' LICENSES folder)" }
[IO.File]::WriteAllText($Output, $out.ToString().Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
